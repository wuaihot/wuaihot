import assert from 'node:assert/strict';
import fs from 'node:fs';
import { reactive } from 'vue';
import { createServer } from 'vite';
const vite=await createServer({server:{middlewareMode:true},appType:'custom',logLevel:'silent'});
try {
 const { matchNavigationEntries,contextSearchLocation }=await vite.ssrLoadModule('/src/utils/navigationSearch.js');
 const route={path:'/rank/douyin/hot',query:{scope:'__all__',q:'old',page:'3',sources:'douyin',from:'today'},hash:'#reader'};
 const location=contextSearchLocation(route,'  亚运  ');
 assert.deepEqual(location,{path:route.path,query:{scope:'__all__',q:'亚运',sources:'douyin',from:'today'},hash:'#reader'});
 assert.equal(route.query.page,'3','search must not mutate the source route');
 assert.equal(route.query.q,'old');
 assert.equal(contextSearchLocation(route,'').query.q,undefined);
 assert.equal(contextSearchLocation(route,'').query.page,undefined);
 const entries=[{id:'topic',label:'AI 专题',name:'ai-topic'},{id:'source',label:'OpenAI',name:'openai-news'},{id:'category',label:'AI',name:'ai'}];
 assert.equal(matchNavigationEntries(entries,'ＡＩ')[0].id,'category','NFKC and exact-title priority');
 assert.deepEqual(matchNavigationEntries(entries,'ai 专题').map(x=>x.id),['topic'],'all query tokens must match');
 assert.equal(matchNavigationEntries(entries,'',24).length,0);
 assert.equal(matchNavigationEntries(entries,'ai',2).length,2,'results must remain bounded');
 assert.equal(matchNavigationEntries(entries,'absent').length,0);
 const noise=[{id:'baidu',label:'百度',name:'baidu'},{id:'kuaishou',label:'快手',name:'kuaishou'},{id:'aichi',label:'2026 亚运会',name:'event:aichi-nagoya-2026'},...entries];
 assert.deepEqual(matchNavigationEntries(noise,'AI').map(item=>item.id),['category','topic','source'],'short AI keyword must not match incidental letters in platform or event slugs');
 const { useContextSearch }=await vite.ssrLoadModule('/src/composables/useContextSearch.js');
 const liveRoute=reactive({path:'/topic/ai',query:{q:'OpenAI',source:'openai',page:'3',sort:'latest'},hash:'#feed'});
 const locations=[];
 const liveSearch=useContextSearch(liveRoute,{replace:location=>{locations.push(location);liveRoute.query=location.query;return Promise.resolve();}});
 assert.equal(liveSearch.value,'OpenAI');
 liveRoute.query.q='Anthropic';
 assert.equal(liveSearch.value,'Anthropic','header/router updates must reach topic filtering');
 liveSearch.value='';
 assert.equal(liveSearch.value,'','topic reset must clear the header query');
 assert.equal(liveRoute.query.source,'openai','clearing search must preserve other filters');
 assert.equal(liveRoute.query.page,undefined,'clearing search must reset pagination');
 assert.equal(locations[0].hash,'#feed');
 const read=path=>fs.readFileSync(path,'utf8');
 const header=read('src/components/Header.vue'),context=read('src/components/ContextToolbar.vue'),nav=read('src/components/ContentNavigation.vue'),search=read('src/components/GlobalSearch.vue'),settings=read('src/components/QuickSettings.vue'),app=read('src/App.vue');
 assert.equal((header.match(/<GlobalSearch/g)||[]).length,1);
 assert.doesNotMatch(context.split('</template>')[0],/context-search|context-toolbar__manager/);
 assert.match(app,/<main[^>]+>[\s\S]{0,60}<ContextToolbar/);
 assert.match(app,/\^\(chigua\|ai\|wool\|game-deals\)-topic/,"topic filtering must preserve the page instance");
 assert.match(nav,/\(hover:hover\) and \(pointer:fine\)/);
 assert.match(nav,/@keydown\.esc/);
 assert.match(nav,/moreCategories/);
 assert.match(search,/@compositionstart/);
 assert.match(search,/cancelUpdate\(\);close\(\)/,'route changes must cancel delayed filtering');
 assert.doesNotMatch(search,/fetch\(|getSharedRanking/,'global discovery must not fan out ranking requests');
 assert.match(settings,/store\.setAppearanceMode/);
 assert.match(settings,/open-hotboard-manager/);
 for (const name of ['AiTopic','GameDealsTopic','ChiguaTopic','WoolTopic']) {
  const topic=read('src/views/'+name+'.vue');
  assert.doesNotMatch(topic.split('<script setup>')[0],/type="search"/,'topics must use the header search');
  assert.match(topic,/const searchQuery = useContextSearch\(route, router\)/);
  assert.doesNotMatch(topic,/window\.history\.replaceState/,'topic filter persistence must update reactive route state');
 }
 const event=read('src/views/EventHub.vue');
 assert.doesNotMatch(event.split('<script setup>')[0],/type="search"/,'event must use the header search');
 assert.match(event,/const eventSearchQuery = computed\([\s\S]{0,180}route\.query\.q/);
 assert.doesNotMatch(event,/handleEventSearchShortcut|eventSearchInput/,'only the header may own search shortcuts');
 console.log('HEADER_SEARCH_CONTRACT_OK: query ownership, normalization, bounds, IME, single entry, task navigation');
} finally { await vite.close(); }
